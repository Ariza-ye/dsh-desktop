import { build } from 'esbuild';
import { existsSync, realpathSync } from 'node:fs';
import { createRequire } from 'node:module';
import { spawnSync } from 'node:child_process';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../', import.meta.url));
const candidates = [];
if (process.env.DSH_PACKAGE_ROOT) candidates.push(path.resolve(process.env.DSH_PACKAGE_ROOT));
if (process.env.DSH_EXECUTABLE && existsSync(process.env.DSH_EXECUTABLE)) {
  let directory = path.dirname(realpathSync(process.env.DSH_EXECUTABLE));
  while (directory !== path.dirname(directory)) {
    if (existsSync(path.join(directory, 'node_modules/@deepseek-ai/dsh-client-shortcuts/lib/protocol.js'))) candidates.push(directory);
    directory = path.dirname(directory);
  }
}
const npm = spawnSync(process.platform === 'win32' ? 'npm.cmd' : 'npm', ['root', '-g'], { encoding: 'utf8', shell: process.platform === 'win32' });
if (npm.status === 0) candidates.push(path.join(npm.stdout.trim(), '@deepseek-ai/dsh'));
try {
  const require = createRequire(import.meta.url);
  candidates.push(path.dirname(require.resolve('@deepseek-ai/dsh/package.json')));
} catch { /* A global install is the usual source. */ }
const dshRoot = candidates.find((directory) => existsSync(path.join(directory, 'node_modules/@deepseek-ai/dsh-client-shortcuts/lib/protocol.js')));
if (!dshRoot) throw new Error('Cannot locate installed DSH shortcut protocol; set DSH_PACKAGE_ROOT to the @deepseek-ai/dsh package directory.');
await build({
  entryPoints: [path.join(root, 'scripts/desktop-bridge-entry.js')],
  outfile: path.join(root, 'src-tauri/src/desktop-bridge.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['safari15.4', 'chrome100'],
  alias: { 'dsh-shortcut-protocol': path.join(dshRoot, 'node_modules/@deepseek-ai/dsh-client-shortcuts/lib/protocol.js') },
  banner: { js: '// Generated by scripts/build-desktop-bridge.mjs from the installed DSH shortcut protocol. Do not edit directly.' },
  legalComments: 'none',
});
console.log(`Desktop bridge bundled from ${dshRoot}`);
